/**
 * Impressive Text Effect
 */

const mumaker = require('mumaker');
const config = require('../../config');

module.exports = {
  name: 'impressive',
  aliases: [],
  category: 'textmaker',
  description: 'Create impressive text effect',
  usage: '.impressive <text>',
  
  async execute(sock, msg, args, context) {
    const { from, reply } = context;
    try {
      const text = args.join(' ');
      if (!text) {
        return reply('Please provide text to generate\nExample: .impressive Nick');
      }
      
      const result = await mumaker.ephoto('https://en.ephoto360.com/create-3d-colorful-paint-text-effect-online-801.html', text);
      
      if (!result || !result.image) {
        throw new Error('No image URL received from the API');
      }
      
      await sock.sendMessage(from, {
        image: { url: result.image },
        caption: `GENERATED BY ${config.botName}`
      }, { quoted: msg });
      
    } catch (error) {
      console.error('Error in impressive command:', error);
      reply(`Error: ${error.message}`);
    }
  }
};
